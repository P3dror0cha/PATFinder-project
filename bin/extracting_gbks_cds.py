from Bio import SeqIO
from Bio.Seq import Seq
from Bio.SeqRecord import SeqRecord
import pandas as pd
import glob
import os
import argparse

def extract_cds_from_gbk(gbk_files):
    """
    Extracts coding sequences (CDS) from GenBank (.gbk) files and saves them to a CSV.

    Scans all files matching the provided pattern, filters features of type
    'CDS', extracts a valid identifier (locus_tag, protein_id, gene, or ID),
    and retrieves the amino acid sequence.

    Args:
        gbk_files (str): Search pattern or path to GenBank files (e.g., "data/*.gbk").

    Returns:
        pd.DataFrame: A DataFrame containing metadata and sequences of the extracted CDS.

    Note:
        This function automatically saves the final DataFrame as a CSV file named
        'all_gbks_cds_sequences.csv' in the current working directory.
    """
    results = []

    for gbk in glob.glob(gbk_files):
        for record in SeqIO.parse(gbk, "genbank"):
            
            cds_features = filter(lambda f: f.type == "CDS", record.features)

            for feature in cds_features:
                qualifiers = feature.qualifiers

                feature_id = (
                    qualifiers.get("locus_tag", [None])[0]
                    or qualifiers.get("protein_id", [None])[0]
                    or qualifiers.get("gene", [None])[0]
                    or qualifiers.get("ID", [None])[0]
                    or "unknown"
                )

                sequence = (
                    qualifiers.get("translation", [None])[0] 
                    or str(feature.extract(record.seq).translate(to_stop=True))
                )

                results.append({
                    "gbk_file": os.path.basename(gbk),
                    "record_id": record.id,
                    "feature_type": feature.type,
                    "feature_id": feature_id,
                    "start": int(feature.location.start),
                    "end": int(feature.location.end),
                    "strand": feature.location.strand,
                    "sequence": sequence
                })
                
    df = pd.DataFrame(results)
    df.to_csv("all_gbks_cds_sequences.csv", index=False)
    
    return df

def filtering_cds(df, output_filename):
    """
    Formats headers, removes duplicates, and exports sequences to a FASTA file.

    Creates a unique identifier for the FASTA header in the format
    'record_id|feature_id_start-end', removes duplicate records based on
    this header, and exports the final sequence dataset.

    Args:
        df (pd.DataFrame): DataFrame generated by `extract_cds_from_gbk`.
        output_filename (str): Name or path for the output FASTA file.

    Returns:
        pd.DataFrame: The filtered DataFrame without duplicate records.
    """

    df["start_end"] = df["start"].astype(str) + "-" + df["end"].astype(str)
    df["fasta_header"] = (
        df["record_id"] + "|" + df["feature_id"] + "_" + df["start_end"]
    )

    df = df.drop_duplicates(subset="fasta_header")
    records = [
        SeqRecord(Seq(seq), id=header_id, description="")
        for header_id, seq in zip(df["fasta_header"], df["sequence"])
    ]

    SeqIO.write(records, output_filename, "fasta")

    return df

if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Extract cds sequences from gbk files"
    )
    parser.add_argument(
        "--input", required=True, help="Path to your gbk files"
    )
    parser.add_argument(
        "--output", required=True, help="Name for the output fasta"
    )

    args = parser.parse_args()
    df_genes = extract_cds_from_gbk(args.input)
    filtering_cds(df_genes, args.output)
