import pandas as pd
import argparse 

from POEM_pipeline_functions import (
    POEM1_parse_operon_string,
    POEM2_process_poem_table
)

def POEM3_operon_pipeline(output_POEM_pipeline_path, output_csv_path):
    df = POEM2_process_poem_table(output_POEM_pipeline_path)
    df = df[["metagenome_id", "strand", "coordinates"]]
    df.to_csv(output_csv_path, index=False)

    return df

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Downstream analysis of POEM results")
    parser.add_argument("--output_POEM", required=True, help="input.fsa.operon file generated by POEM pipeline")
    parser.add_argument("--output_csv", default="POEM_operon_filtered.csv", help="Path to save the filtered CSV output")

    args = parser.parse_args()

    POEM3_operon_pipeline(
        output_POEM_pipeline_path=args.output_POEM,
        output_csv_path=args.output_csv
    )