#!/usr/bin/env python3

"""Plot quality and assembly metrics from MGnify genome metadata."""

import os
import tempfile
from pathlib import Path

os.environ.setdefault(
    "MPLCONFIGDIR",
    str(Path(tempfile.gettempdir()) / "patfinder_matplotlib"),
)

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns


REQUIRED_TEXT_COLUMNS = {
    "accession",
    "taxon_lineage",
}

REQUIRED_NUMERIC_COLUMNS = {
    "completeness",
    "contamination",
    "quality_score",
    "length",
    "num_contigs",
    "n50",
    "gc_content",
    "num_proteins",
}

REQUIRED_COLUMNS = REQUIRED_TEXT_COLUMNS | REQUIRED_NUMERIC_COLUMNS

QUALITY_GROUP_ORDER = [
    "Limiar ≥90% / ≤5%",
    "Apenas limiar ≥50% / ≤10%",
    "Fora desses limiares",
]

QUALITY_GROUP_COLORS = {
    "Limiar ≥90% / ≤5%": "#2A9D8F",
    "Apenas limiar ≥50% / ≤10%": "#E9C46A",
    "Fora desses limiares": "#E76F51",
}


def G1_load_genome_metadata(input_csv):
    """Load, validate and enrich an MGnify genome metadata CSV.

    Parameters
    ----------
    input_csv : str or pathlib.Path
        CSV generated by ``D5_save_genome_metadata``.

    Returns
    -------
    pandas.DataFrame
        Validated metadata with derived plotting columns.

    Raises
    ------
    FileNotFoundError
        If ``input_csv`` does not exist.
    ValueError
        If the CSV is empty, lacks required columns, contains duplicated
        accessions, or contains invalid/missing numeric values.
    """

    input_csv = Path(input_csv)

    if not input_csv.is_file():
        raise FileNotFoundError(f"Metadata CSV not found: {input_csv}")

    metadata = pd.read_csv(input_csv)

    if metadata.empty:
        raise ValueError(f"Metadata CSV is empty: {input_csv}")

    missing_columns = sorted(REQUIRED_COLUMNS - set(metadata.columns))

    if missing_columns:
        raise ValueError(
            "Metadata CSV is missing required columns: "
            + ", ".join(missing_columns)
        )

    duplicated_accessions = metadata.loc[
        metadata["accession"].duplicated(), "accession"
    ].astype(str)

    if not duplicated_accessions.empty:
        raise ValueError(
            "Duplicated accessions in metadata CSV: "
            + ", ".join(sorted(duplicated_accessions.unique()))
        )

    for column in sorted(REQUIRED_NUMERIC_COLUMNS):
        metadata[column] = pd.to_numeric(metadata[column], errors="coerce")

    invalid_columns = [
        column
        for column in sorted(REQUIRED_NUMERIC_COLUMNS)
        if metadata[column].isna().any()
    ]

    if invalid_columns:
        raise ValueError(
            "Missing or non-numeric values in columns: "
            + ", ".join(invalid_columns)
        )

    if (metadata["length"] <= 0).any():
        raise ValueError("Column 'length' must contain values greater than zero.")

    metadata = metadata.copy()
    metadata["length_mb"] = metadata["length"] / 1_000_000
    metadata["n50_kb"] = metadata["n50"] / 1_000
    metadata["proteins_per_mb"] = (
        metadata["num_proteins"] / metadata["length_mb"]
    )

    high_threshold = (
        (metadata["completeness"] >= 90)
        & (metadata["contamination"] <= 5)
    )
    medium_threshold = (
        (metadata["completeness"] >= 50)
        & (metadata["contamination"] <= 10)
    )

    metadata["quality_threshold_group"] = QUALITY_GROUP_ORDER[2]
    metadata.loc[medium_threshold, "quality_threshold_group"] = (
        QUALITY_GROUP_ORDER[1]
    )
    metadata.loc[high_threshold, "quality_threshold_group"] = (
        QUALITY_GROUP_ORDER[0]
    )

    return metadata


def _prepare_output_dir(output_dir):
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir


def _save_figure(figure, output_dir, filename, dpi=300):
    output_path = _prepare_output_dir(output_dir) / filename
    figure.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(figure)
    return output_path


def _set_plot_style():
    sns.set_theme(style="whitegrid", context="notebook")
    plt.rcParams.update(
        {
            "axes.titleweight": "bold",
            "figure.dpi": 120,
            "savefig.facecolor": "white",
        }
    )


def G2_plot_completeness_contamination(
    metadata,
    output_dir="MGnify_plots",
    output_prefix="aquatic",
    annotate=False,
):
    """Plot completeness versus contamination for every MAG.

    The dashed lines show the 90% completeness and 5% contamination
    thresholds; they do not by themselves establish the complete MIMAG
    high-quality classification.
    """

    _set_plot_style()
    figure, axis = plt.subplots(figsize=(8.5, 6.5))
    present_groups = [
        group
        for group in QUALITY_GROUP_ORDER
        if group in set(metadata["quality_threshold_group"])
    ]

    sns.scatterplot(
        data=metadata,
        x="contamination",
        y="completeness",
        hue="quality_threshold_group",
        hue_order=present_groups,
        palette=QUALITY_GROUP_COLORS,
        s=105,
        alpha=0.85,
        edgecolor="white",
        linewidth=0.7,
        ax=axis,
    )

    axis.axvline(5, color="#555555", linestyle="--", linewidth=1)
    axis.axhline(90, color="#555555", linestyle="--", linewidth=1)

    if annotate:
        for row in metadata.itertuples(index=False):
            axis.annotate(
                row.accession,
                (row.contamination, row.completeness),
                xytext=(4, 4),
                textcoords="offset points",
                fontsize=7,
                alpha=0.8,
            )

    axis.set(
        title="Completude e contaminação dos MAGs",
        xlabel="Contaminação (%)",
        ylabel="Completude (%)",
    )
    axis.set_xlim(left=0, right=max(6, metadata["contamination"].max() * 1.12))
    axis.set_ylim(
        bottom=max(0, metadata["completeness"].min() - 5),
        top=101,
    )
    axis.legend(
        title="Completude / contaminação",
        loc="lower right",
        frameon=True,
    )
    figure.tight_layout()

    return _save_figure(
        figure,
        output_dir,
        f"{output_prefix}_completeness_contamination.png",
    )


def G3_plot_metric_distributions(
    metadata,
    output_dir="MGnify_plots",
    output_prefix="aquatic",
):
    """Plot distributions of six quality and assembly metrics."""

    _set_plot_style()
    figure, axes = plt.subplots(2, 4, figsize=(17, 8.5))

    metrics = [
        ("completeness", "Completude (%)", "#2A9D8F", 2),
        ("contamination", "Contaminação (%)", "#E76F51", 2),
        ("quality_score", "Quality score", "#E9C46A", 2),
        ("length_mb", "Tamanho do MAG (Mb)", "#457B9D", 2),
        ("n50_kb", "N50 (kb)", "#6A4C93", 2),
        ("num_contigs", "Número de contigs", "#F4A261", 0),
        ("gc_content", "Conteúdo GC (%)", "#588157", 2),
        ("proteins_per_mb", "Proteínas preditas por Mb", "#277DA1", 1),
    ]

    for axis, (column, label, color, decimal_places) in zip(axes.flat, metrics):
        median = metadata[column].median()
        sns.histplot(
            data=metadata,
            x=column,
            bins="auto",
            color=color,
            edgecolor="white",
            alpha=0.9,
            ax=axis,
        )
        axis.axvline(
            median,
            color="#222222",
            linestyle="--",
            linewidth=1.2,
            label=f"Mediana: {median:.{decimal_places}f}",
        )
        axis.set(xlabel=label, ylabel="Número de MAGs")
        axis.legend(frameon=False, fontsize=9)

    figure.suptitle(
        "Distribuição das métricas dos MAGs",
        fontsize=16,
        fontweight="bold",
        y=1.01,
    )
    figure.tight_layout()

    return _save_figure(
        figure,
        output_dir,
        f"{output_prefix}_metric_distributions.png",
    )


def G4_plot_proteins_vs_length(
    metadata,
    output_dir="MGnify_plots",
    output_prefix="aquatic",
    annotate=False,
):
    """Plot genome length versus predicted protein count.

    Point color represents proteins per megabase, which makes comparisons less
    dependent on total genome size.
    """

    _set_plot_style()
    figure, axis = plt.subplots(figsize=(8.5, 6.5))

    points = axis.scatter(
        metadata["length_mb"],
        metadata["num_proteins"],
        c=metadata["proteins_per_mb"],
        cmap="viridis",
        s=85,
        alpha=0.85,
        edgecolors="white",
        linewidths=0.7,
    )

    if annotate:
        for row in metadata.itertuples(index=False):
            axis.annotate(
                row.accession,
                (row.length_mb, row.num_proteins),
                xytext=(4, 4),
                textcoords="offset points",
                fontsize=7,
                alpha=0.8,
            )

    colorbar = figure.colorbar(points, ax=axis, pad=0.02)
    colorbar.set_label("Proteínas preditas por Mb")

    axis.set(
        title="Tamanho do MAG e número de proteínas preditas",
        xlabel="Tamanho do MAG (Mb)",
        ylabel="Número de proteínas preditas",
    )
    figure.tight_layout()

    return _save_figure(
        figure,
        output_dir,
        f"{output_prefix}_proteins_vs_length.png",
    )


def G5_plot_quality_threshold_summary(
    metadata,
    output_dir="MGnify_plots",
    output_prefix="aquatic",
):
    """Plot counts of MAGs grouped by completeness/contamination thresholds."""

    _set_plot_style()
    counts = (
        metadata["quality_threshold_group"]
        .value_counts()
        .reindex(QUALITY_GROUP_ORDER, fill_value=0)
        .rename_axis("quality_threshold_group")
        .reset_index(name="count")
    )
    counts = counts[counts["count"] > 0]

    figure, axis = plt.subplots(figsize=(9, 5.5))
    bars = sns.barplot(
        data=counts,
        x="count",
        y="quality_threshold_group",
        hue="quality_threshold_group",
        palette=QUALITY_GROUP_COLORS,
        legend=False,
        ax=axis,
    )

    for container in bars.containers:
        bars.bar_label(container, padding=4, fontsize=11)

    axis.set(
        title="MAGs por limiares de completude e contaminação",
        xlabel="Número de MAGs",
        ylabel=None,
    )
    axis.set_xlim(0, max(counts["count"].max() * 1.15, 1))
    figure.tight_layout()

    return _save_figure(
        figure,
        output_dir,
        f"{output_prefix}_quality_threshold_summary.png",
    )


def _extract_taxonomic_rank(lineage, rank_prefix):
    if pd.isna(lineage):
        return "Não classificado"

    for taxon in str(lineage).split(";"):
        taxon = taxon.strip()

        if taxon.startswith(rank_prefix):
            name = taxon.removeprefix(rank_prefix).strip()
            return name or "Não classificado"

    return "Não classificado"


def G6_plot_taxonomic_distribution(
    metadata,
    output_dir="MGnify_plots",
    output_prefix="aquatic",
    rank="phylum",
):
    """Plot MAG counts by a taxonomic rank from ``taxon_lineage``.

    The chart describes the selected MAG set and must not be interpreted as
    organism abundance in the original environmental samples.
    """

    rank_settings = {
        "phylum": ("p__", "filo"),
        "class": ("c__", "classe"),
        "order": ("o__", "ordem"),
        "family": ("f__", "família"),
        "genus": ("g__", "gênero"),
    }

    if rank not in rank_settings:
        valid_ranks = ", ".join(rank_settings)
        raise ValueError(f"Invalid taxonomic rank '{rank}'. Use: {valid_ranks}")

    rank_prefix, rank_label = rank_settings[rank]
    taxa = metadata["taxon_lineage"].map(
        lambda lineage: _extract_taxonomic_rank(lineage, rank_prefix)
    )
    counts = (
        taxa.value_counts()
        .rename_axis("taxon")
        .reset_index(name="count")
        .sort_values(["count", "taxon"], ascending=[False, True])
    )
    counts["percentage"] = counts["count"] / counts["count"].sum() * 100

    _set_plot_style()
    figure_height = max(4.8, 0.55 * len(counts) + 2.2)
    figure, axis = plt.subplots(figsize=(9, figure_height))

    bars = sns.barplot(
        data=counts,
        x="count",
        y="taxon",
        color="#457B9D",
        ax=axis,
    )
    labels = [
        f"{count} ({percentage:.1f}%)"
        for count, percentage in zip(counts["count"], counts["percentage"])
    ]

    for container in bars.containers:
        bars.bar_label(container, labels=labels, padding=4, fontsize=10)

    axis.set(
        title=f"Distribuição taxonômica dos MAGs por {rank_label}",
        xlabel="Número de MAGs",
        ylabel=rank_label.capitalize(),
    )
    axis.set_xlim(0, max(counts["count"].max() * 1.25, 1))
    figure.text(
        0.01,
        0.01,
        "Contagem dos MAGs selecionados; não representa abundância ambiental.",
        fontsize=9,
        color="#555555",
    )
    figure.tight_layout(rect=(0, 0.035, 1, 1))

    return _save_figure(
        figure,
        output_dir,
        f"{output_prefix}_taxonomic_distribution_{rank}.png",
    )


def G7_generate_genome_metadata_plots(
    input_csv,
    output_dir="MGnify_plots",
    output_prefix="aquatic",
    annotate=False,
):
    """Generate all MGnify metadata plots and return their paths."""

    metadata = G1_load_genome_metadata(input_csv)

    output_paths = [
        G2_plot_completeness_contamination(
            metadata,
            output_dir=output_dir,
            output_prefix=output_prefix,
            annotate=annotate,
        ),
        G3_plot_metric_distributions(
            metadata,
            output_dir=output_dir,
            output_prefix=output_prefix,
        ),
        G4_plot_proteins_vs_length(
            metadata,
            output_dir=output_dir,
            output_prefix=output_prefix,
            annotate=annotate,
        ),
        G5_plot_quality_threshold_summary(
            metadata,
            output_dir=output_dir,
            output_prefix=output_prefix,
        ),
        G6_plot_taxonomic_distribution(
            metadata,
            output_dir=output_dir,
            output_prefix=output_prefix,
        ),
    ]

    return output_paths