#!/usr/bin/env python3

"""Command-line entry point for MGnify genome metadata plots."""

import argparse

from MGnify_plot_functions import G7_generate_genome_metadata_plots


def main():
    parser = argparse.ArgumentParser(
        description="Generate plots from an MGnify genome metadata CSV."
    )
    parser.add_argument(
        "input_csv",
        help="CSV generated by D5_save_genome_metadata",
    )
    parser.add_argument(
        "--output_dir",
        default="MGnify_plots",
        help="Directory used to save plot files",
    )
    parser.add_argument(
        "--output_prefix",
        default="aquatic",
        help="Prefix used in plot filenames",
    )
    parser.add_argument(
        "--annotate",
        action="store_true",
        help="Add MGYG accessions beside scatter-plot points",
    )

    args = parser.parse_args()

    output_paths = G7_generate_genome_metadata_plots(
        input_csv=args.input_csv,
        output_dir=args.output_dir,
        output_prefix=args.output_prefix,
        annotate=args.annotate,
    )

    print(f"Generated {len(output_paths)} MGnify plot files:")
    for output_path in output_paths:
        print(f"- {output_path}")


if __name__ == "__main__":
    main()