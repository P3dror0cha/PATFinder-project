#!/usr/bin/env python3

import pandas as pd
import requests
import re
import argparse 

from kofam_analysis_functions import (
    K1_kofam_import, 
    K2_kofam_best_hits,
    K3_kofam_without_best_hits,
    K4_KEGG_API_information,
    K5_merging_kofam_df,
    K6_uniting_BGC_information,
    K7_kegg_ids_filtering,
    K8_uniting_all_information
    )

def K9_kofam_pipeline(kofam_result_list, filtered_bigscape_results, output_path_raw_csv, output_path_filtered_csv):

    kofam_results = K1_kofam_import(kofam_result_list)
    kofam_best_hits = K2_kofam_best_hits(kofam_results)
    final_df_filtered = K3_kofam_without_best_hits(kofam_results, kofam_best_hits)
    df_kegg, df_list = K4_KEGG_API_information()
    df_groupby = K5_merging_kofam_df(final_df_filtered, df_list, df_kegg)
    
    df_bgc = K6_uniting_BGC_information(filtered_bigscape_results, df_groupby)
    df_bgc["filtered_pathways"] = df_bgc["pathway"].apply(K7_kegg_ids_filtering)
    df_bgc.rename(columns={"percentual": "KO_quality_percentual"}, inplace=True)
    
    df_bgc, df_bgc_filtered = K8_uniting_all_information(df_bgc, output_path_raw_csv, output_path_filtered_csv)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Downstream analysis of KOFAM results")
    parser.add_argument("--kofam_results", required=True, help="kofam.out file generated by KofamScan")
    parser.add_argument("--bgc_dir", required=True, help="Folder containing all GBK files")
    parser.add_argument("--out_raw", default="kofam_raw_results.csv", help="Name of the raw output CSV")
    parser.add_argument("--out_filtered", default="kofam_filtered_results.csv", help="Name of the filtered output CSV")
    
    args = parser.parse_args()

    K9_kofam_pipeline(
        kofam_result_list=args.kofam_results, 
        filtered_bigscape_results=args.bgc_dir, 
        output_path_raw_csv=args.out_raw, 
        output_path_filtered_csv=args.out_filtered
    )